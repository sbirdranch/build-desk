// Isolated browser acceptance environment. Never writes sample orders to the live tracker.
import {readFile,writeFile,copyFile,mkdir,open} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import {spawn} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),dir=path.join(root,'web/test-output/purchasing-browser',randomUUID());
await mkdir(dir,{recursive:true});
const registry=JSON.parse(await readFile(path.join(root,'config/builds.json'),'utf8')),b=registry.builds.find(b=>b.id==='kitten-745');
if(!b)throw Error('Kitten test build is not registered.');
await copyFile(path.resolve(root,b.store.path),path.join(dir,'Clone.xlsx'));
b.name+=' — TEST COPY';b.store.path=path.join(dir,'Clone.xlsx');b.printer={id:'purchasing-browser-test',name:'Test printer (disconnected)'};registry.builds=[b];
const queueDir=path.join(dir,'local-data',b.id,'order-updates');await mkdir(queueDir,{recursive:true});
const raw=await readFile(path.join(root,'docs/order-updates/fixtures/partial-shipment.valid.json'),'utf8');
await writeFile(path.join(queueDir,'cache.json'),JSON.stringify({lastCheck:null,error:'Isolated fixture queue: no Google authorization configured.',files:[{id:'fixture-drive-file',name:'fixture.json',raw}],acknowledged:[]}));
const registryFile=path.join(dir,'builds.json');await writeFile(registryFile,JSON.stringify(registry));
const out=await open(path.join(dir,'server.log'),'a'),err=await open(path.join(dir,'server.err.log'),'a');
const child=spawn(process.execPath,['server.mjs'],{cwd:path.join(root,'web'),env:{...process.env,PORT:'4175',BUILDDESK_QUEUE_ROOT:dir,BUILDDESK_REGISTRY:registryFile},detached:true,windowsHide:true,stdio:['ignore',out.fd,err.fd]});child.unref();
await writeFile(path.join(root,'web/test-output/purchasing-browser/latest.json'),JSON.stringify({pid:child.pid,dir}));
console.log('Disposable Purchasing test: http://127.0.0.1:4175/ (PID '+child.pid+')');
